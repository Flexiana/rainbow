(ns rainbow.math.rational.nnrat.distance
  "A quotient-safe computational distance on exact nonnegative rationals.

  For x=nx/dx and y=ny/dy, `nnrat/distance x y` is represented by

      |nx*dy - ny*dx| / (dx*dy).

  The numerator uses the existing computational `nat/distance`; the packed
  denominator uses the same positive denominator-combination operation as
  NNRAT addition and multiplication.  The main theorem identifies this value
  exactly with the additive-radius interface used by finite Bellman proofs:

      distance x y <= epsilon
        iff
      x <= y + epsilon  and  y <= x + epsilon.

  All denominator transports are checked equalities generated by the verified
  nat-ring normalizer.  Native, kernel-checked, and axiom-free on D63."
  (:require [rainbow.module :as module]
            [rainbow.math.logic.function :as function]
            [rainbow.math.milestone-support :as support]
            [rainbow.math.nat.contraction :as contraction]
            [rainbow.math.nat.distance-radius :as radius]
            [rainbow.math.nat.ring :as ring]
            [rainbow.math.rational.nnrat.order-equivalence :as order-equivalence]
            [rainbow.math.logic.proposition :as proposition]))

(def type-level [:succ [:zero]])
(def nat (function/const* 'data/Nat []))
(def successor (function/const* 'data/succ []))
(def nnrat (function/const* 'nnrat/NonnegativeRational []))

(defn- app [f & xs] (apply function/app f xs))
(defn- succ [value] (app successor value))
(defn- nnum [value]
  (app (function/const* 'nnrat/numerator []) value))
(defn- dpre [value]
  (app (function/const* 'nnrat/denominator-predecessor []) value))
(defn- den [value]
  (app (function/const* 'nnrat/denominator []) value))
(defn- combine [left right]
  (app (function/const* 'nnrat/combine-denominator-predecessors [])
       left right))
(defn- make [numerator denominator-predecessor]
  (app (function/const* 'nnrat/make [])
       numerator denominator-predecessor))
(defn- nadd [left right]
  (app (function/const* 'algebra/nat-add []) left right))
(defn- nmul [left right]
  (app (function/const* 'nat/multiply []) left right))
(defn- ndistance [left right]
  (app (function/const* 'nat/distance []) left right))
(defn- nat-at-most [left right]
  (app (function/const* 'nat/at-most []) left right))
(defn- radd [left right]
  (app (function/const* 'nnrat/add []) left right))
(defn- rat-distance [left right]
  (app (function/const* 'nnrat/distance []) left right))
(defn- rle [left right]
  (app (function/const* 'nnrat/at-most []) left right))
(defn- req [left right]
  (app (function/const* 'nnrat/equivalent []) left right))
(defn- close [left right epsilon]
  (proposition/conjunction
   (rle left (radd right epsilon))
   (rle right (radd left epsilon))))
(defn- to-cross [left right ordered]
  (app (function/const* 'nnrat/at-most-to-cross [])
       left right ordered))
(defn- from-cross [left right ordered]
  (app (function/const* 'nnrat/at-most-from-cross [])
       left right ordered))
(defn- rewrite-left [left replacement right same ordered]
  (app (function/const* 'nat/at-most-rewrite-left [])
       left replacement right same ordered))
(defn- rewrite-right [left right replacement same ordered]
  (app (function/const* 'nat/at-most-rewrite-right [])
       left right replacement same ordered))

(defn- combine-law [left right]
  {:lhs (succ (combine (dpre left) (dpre right)))
   :rhs (nmul (den left) (den right))
   :proof
   (app (function/const* 'nnrat/denominator-combine [])
        (dpre left) (dpre right))})

(defn- cross-components [left right epsilon]
  (let [nl (nnum left) dl (den left)
        nr (nnum right) dr (den right)
        ne (nnum epsilon) de (den epsilon)
        left-cross (nmul nl dr)
        right-cross (nmul nr dl)]
    {:nl nl :dl dl :nr nr :dr dr :ne ne :de de
     :left-cross left-cross
     :right-cross right-cross
     :scaled-left (nmul left-cross de)
     :scaled-right (nmul right-cross de)
     :scaled-radius (nmul ne (nmul dl dr))}))

(defn- additive-cross-to-normalized
  [left right epsilon ordered]
  (let [{:keys [nl dl nr dr ne de scaled-left scaled-right scaled-radius]}
        (cross-components left right epsilon)
        packed-den (succ (combine (dpre right) (dpre epsilon)))
        raw-left (nmul nl packed-den)
        raw-right (nmul (nadd (nmul nr de) (nmul ne dr)) dl)
        normalized-right (nadd scaled-right scaled-radius)
        raw-left-to-normalized
        (ring/chain
         (ring/cong-mul-right nl (combine-law right epsilon))
         (ring/prove-nat-eq (nmul nl (nmul dr de)) scaled-left))
        raw-right-to-normalized
        (ring/prove-nat-eq raw-right normalized-right)
        left-normalized
        (rewrite-left
         scaled-left raw-left raw-right
         (:proof (ring/symp raw-left-to-normalized)) ordered)]
    (rewrite-right
     scaled-left raw-right normalized-right
     (:proof raw-right-to-normalized) left-normalized)))

(defn- normalized-to-additive-cross
  [left right epsilon ordered]
  (let [{:keys [nl dl nr dr ne de scaled-left scaled-right scaled-radius]}
        (cross-components left right epsilon)
        packed-den (succ (combine (dpre right) (dpre epsilon)))
        raw-left (nmul nl packed-den)
        raw-right (nmul (nadd (nmul nr de) (nmul ne dr)) dl)
        normalized-right (nadd scaled-right scaled-radius)
        raw-left-to-normalized
        (ring/chain
         (ring/cong-mul-right nl (combine-law right epsilon))
         (ring/prove-nat-eq (nmul nl (nmul dr de)) scaled-left))
        raw-right-to-normalized
        (ring/prove-nat-eq raw-right normalized-right)
        raw-left-bound
        (rewrite-left
         raw-left scaled-left normalized-right
         (:proof raw-left-to-normalized) ordered)]
    (rewrite-right
     raw-left normalized-right raw-right
     (:proof (ring/symp raw-right-to-normalized)) raw-left-bound)))

(defn- distance-cross-to-normalized
  [left right epsilon ordered]
  (let [{:keys [left-cross right-cross ne de dl dr scaled-left
                scaled-right scaled-radius]}
        (cross-components left right epsilon)
        delta (ndistance left-cross right-cross)
        scaled-delta (nmul delta de)
        distance-scaled (ndistance scaled-left scaled-right)
        packed-den (succ (combine (dpre left) (dpre right)))
        raw-right (nmul ne packed-den)
        raw-right-to-radius
        (ring/chain
         (ring/cong-mul-right ne (combine-law left right))
         (ring/prove-nat-eq (nmul ne (nmul dl dr)) scaled-radius))
        radius-bound
        (rewrite-right
         scaled-delta raw-right scaled-radius
         (:proof raw-right-to-radius) ordered)
        scaled-distance-law
        (app (function/const* 'nat/distance-multiply-right [])
             left-cross right-cross de)]
    (rewrite-left
     distance-scaled scaled-delta scaled-radius
     scaled-distance-law radius-bound)))

(defn- normalized-to-distance-cross
  [left right epsilon ordered]
  (let [{:keys [left-cross right-cross ne de dl dr scaled-left
                scaled-right scaled-radius]}
        (cross-components left right epsilon)
        delta (ndistance left-cross right-cross)
        scaled-delta (nmul delta de)
        distance-scaled (ndistance scaled-left scaled-right)
        packed-den (succ (combine (dpre left) (dpre right)))
        raw-right (nmul ne packed-den)
        raw-right-to-radius
        (ring/chain
         (ring/cong-mul-right ne (combine-law left right))
         (ring/prove-nat-eq (nmul ne (nmul dl dr)) scaled-radius))
        scaled-distance-law
        (app (function/const* 'nat/distance-multiply-right [])
             left-cross right-cross de)
        scaled-delta-bound
        (rewrite-left
         scaled-delta distance-scaled scaled-radius
         (app (function/const* 'equality/symmetric [type-level])
              nat distance-scaled scaled-delta scaled-distance-law)
         ordered)]
    (rewrite-right
     scaled-delta scaled-radius raw-right
     (:proof (ring/symp raw-right-to-radius)) scaled-delta-bound)))

(def distance-spec
  {:name 'nnrat/distance
   :kind :definition
   :universes []
   :transparency :reducible
   :type (function/arrow nnrat nnrat nnrat)
   :value
   (function/lam
    [['left nnrat] ['right nnrat]]
    (make
     (ndistance
      (nmul (nnum 'left) (den 'right))
      (nmul (nnum 'right) (den 'left)))
     (combine (dpre 'left) (dpre 'right))))})

(def additive-closeness-of-distance-at-most-spec
  {:name 'nnrat/additive-closeness-of-distance-at-most
   :universes []
   :type
   (function/forall
    [['left nnrat] ['right nnrat] ['epsilon nnrat]
     ['bounded (rle (rat-distance 'left 'right) 'epsilon)]]
    (close 'left 'right 'epsilon))
   :value
   (function/lam
    [['left nnrat] ['right nnrat] ['epsilon nnrat]
     ['bounded (rle (rat-distance 'left 'right) 'epsilon)]]
    (let [{:keys [scaled-left scaled-right scaled-radius]}
          (cross-components 'left 'right 'epsilon)
          swapped-components
          (cross-components 'right 'left 'epsilon)
          swapped-radius (:scaled-radius swapped-components)
          normalized
          (distance-cross-to-normalized
           'left 'right 'epsilon
           (to-cross (rat-distance 'left 'right) 'epsilon 'bounded))
          bounds
          (app
           (function/const* 'nat/additive-bounds-of-distance-at-most [])
           scaled-left scaled-right scaled-radius normalized)
          left-bound
          (app (function/const* 'proposition/left [])
               (nat-at-most scaled-left (nadd scaled-right scaled-radius))
               (nat-at-most scaled-right (nadd scaled-left scaled-radius))
               bounds)
          right-bound
          (app (function/const* 'proposition/right [])
               (nat-at-most scaled-left (nadd scaled-right scaled-radius))
               (nat-at-most scaled-right (nadd scaled-left scaled-radius))
               bounds)
          right-bound-commuted
          (rewrite-right
           scaled-right
           (nadd scaled-left scaled-radius)
           (nadd scaled-left swapped-radius)
           (:proof
            (ring/prove-nat-eq
             (nadd scaled-left scaled-radius)
             (nadd scaled-left swapped-radius)))
           right-bound)
          left-close
          (from-cross
           'left (radd 'right 'epsilon)
           (normalized-to-additive-cross
            'left 'right 'epsilon left-bound))
          right-close
          (from-cross
           'right (radd 'left 'epsilon)
           (normalized-to-additive-cross
            'right 'left 'epsilon right-bound-commuted))]
      (app (function/const* 'proposition/conjoin [])
           (rle 'left (radd 'right 'epsilon))
           (rle 'right (radd 'left 'epsilon))
           left-close right-close)))})

(def distance-at-most-of-additive-closeness-spec
  {:name 'nnrat/distance-at-most-of-additive-closeness
   :universes []
   :type
   (function/forall
    [['left nnrat] ['right nnrat] ['epsilon nnrat]
     ['left-close (rle 'left (radd 'right 'epsilon))]
     ['right-close (rle 'right (radd 'left 'epsilon))]]
    (rle (rat-distance 'left 'right) 'epsilon))
   :value
   (function/lam
    [['left nnrat] ['right nnrat] ['epsilon nnrat]
     ['left-close (rle 'left (radd 'right 'epsilon))]
     ['right-close (rle 'right (radd 'left 'epsilon))]]
    (let [{:keys [scaled-left scaled-right scaled-radius]}
          (cross-components 'left 'right 'epsilon)
          swapped-components
          (cross-components 'right 'left 'epsilon)
          swapped-radius (:scaled-radius swapped-components)
          left-bound
          (additive-cross-to-normalized
           'left 'right 'epsilon
           (to-cross 'left (radd 'right 'epsilon) 'left-close))
          right-bound-swapped
          (additive-cross-to-normalized
           'right 'left 'epsilon
           (to-cross 'right (radd 'left 'epsilon) 'right-close))
          right-bound
          (rewrite-right
           scaled-right
           (nadd scaled-left swapped-radius)
           (nadd scaled-left scaled-radius)
           (:proof
            (ring/prove-nat-eq
             (nadd scaled-left swapped-radius)
             (nadd scaled-left scaled-radius)))
           right-bound-swapped)
          distance-bound
          (app
           (function/const* 'nat/distance-at-most-of-additive-bounds [])
           scaled-left scaled-right scaled-radius
           left-bound right-bound)]
      (from-cross
       (rat-distance 'left 'right) 'epsilon
       (normalized-to-distance-cross
        'left 'right 'epsilon distance-bound))))})

(def distance-at-most-iff-additive-closeness-spec
  {:name 'nnrat/distance-at-most-iff-additive-closeness
   :universes []
   :type
   (function/forall
    [['left nnrat] ['right nnrat] ['epsilon nnrat]]
    (proposition/equivalence
     (rle (rat-distance 'left 'right) 'epsilon)
     (close 'left 'right 'epsilon)))
   :value
   (function/lam
    [['left nnrat] ['right nnrat] ['epsilon nnrat]]
    (let [bounded (rle (rat-distance 'left 'right) 'epsilon)
          left-close (rle 'left (radd 'right 'epsilon))
          right-close (rle 'right (radd 'left 'epsilon))
          close-evidence (proposition/conjunction left-close right-close)]
      (app
       (function/const* 'proposition/equivalence-intro [])
       bounded close-evidence
       (function/lam
        [['evidence bounded]]
        (app
         (function/const* 'nnrat/additive-closeness-of-distance-at-most [])
         'left 'right 'epsilon 'evidence))
       (function/lam
        [['evidence close-evidence]]
        (app
         (function/const* 'nnrat/distance-at-most-of-additive-closeness [])
         'left 'right 'epsilon
         (app (function/const* 'proposition/left [])
              left-close right-close 'evidence)
         (app (function/const* 'proposition/right [])
              left-close right-close 'evidence))))))})

(def distance-symmetric-spec
  {:name 'nnrat/distance-symmetric
   :universes []
   :type
   (function/forall
    [['left nnrat] ['right nnrat]]
    (req (rat-distance 'left 'right)
         (rat-distance 'right 'left)))
   :value
   (function/lam
    [['left nnrat] ['right nnrat]]
    (let [left-cross (nmul (nnum 'left) (den 'right))
          right-cross (nmul (nnum 'right) (den 'left))
          forward-distance (ndistance left-cross right-cross)
          reverse-distance (ndistance right-cross left-cross)
          forward-den (succ (combine (dpre 'left) (dpre 'right)))
          reverse-den (succ (combine (dpre 'right) (dpre 'left)))
          common-den (nmul (den 'left) (den 'right))
          left-path
          (ring/chain
           (ring/cong-mul-right
            forward-distance (combine-law 'right 'left))
           (ring/prove-nat-eq
            (nmul forward-distance
                  (nmul (den 'right) (den 'left)))
            (nmul forward-distance common-den)))
          distance-same
          {:lhs reverse-distance :rhs forward-distance
           :proof
           (app (function/const* 'nat/distance-commutative [])
                right-cross left-cross)}
          right-path
          (ring/chain
           (ring/cong-mul-left forward-den distance-same)
           (ring/chain
            (ring/cong-mul-right
             forward-distance (combine-law 'left 'right))
            (ring/prove-nat-eq
             (nmul forward-distance common-den)
             (nmul forward-distance common-den))))]
      (:proof (ring/chain left-path (ring/symp right-path)))))})

